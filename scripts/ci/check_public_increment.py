def read_public_text(repo: Path, blob: str) -> bytes:
    # Caller has already rejected all known source identities and archives.
    size = int(_git(repo, "cat-file", "-s", blob))
    if size > 2_000_000:
        raise ValueError("LARGE_PUBLIC_INCREMENT_REQUIRES_REVIEW")
    return _git(repo, "cat-file", "blob", blob)


def _business_object(value: object) -> bool:
    if isinstance(value, dict):
        for key, item in value.items():
            if (
                key in {"farm_to_base", "base_members", "factory_aliases"}
                and isinstance(item, (dict, list))
                and item
            ):
                return True
            if (
                isinstance(key, str)
                and QUANTITIES.search(key)
                and (type(item) in {int, float} or isinstance(item, str) and NUMBER.fullmatch(item))
            ):
                return True
        names = [
            item
            for key, item in value.items()
            if isinstance(key, str)
            and IDENTITIES.search(key)
            and isinstance(item, str)
            and item not in {"string", "number"}
        ]
        if names:
            return True
        return any(_business_object(item) for item in value.values())
    if isinstance(value, list):
        return any(_business_object(item) for item in value)
    return False


def _source_object(value: object) -> bool:
    if isinstance(value, dict):
        for key, item in value.items():
            if (
                key in {"source_path", "input_path", "source_file"}
                and isinstance(item, str)
                and RAW_PATH.search(item)
            ):
                return True
        return any(_source_object(item) for item in value.values())
    if isinstance(value, list):
        return any(_source_object(item) for item in value)
    return False


def text_reason(path: str, data: bytes) -> str | None:
    suffix = PurePosixPath(path).suffix.lower()
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return "UNVERIFIED_BINARY_INCREMENT"
    if suffix == ".csv":
        # Empty templates are schemas; nonempty data needs provenance. The
        # generated classification CSV is separately checked by exact bytes.
        return "UNVERIFIED_DATA_ARTIFACT" if len(list(csv.reader(io.StringIO(text)))) > 1 else None
    value: object = None
    if text.lstrip().startswith(("{", "[")):
        try:
            value = json.loads(text)
        except ValueError:
            if suffix == ".json":
                return "UNPARSEABLE_STRUCTURED_INCREMENT"
    if value is None and suffix in {".json", ".yaml", ".yml"}:
        try:
            value = json.loads(text) if suffix == ".json" else yaml.safe_load(text)
        except (ValueError, yaml.YAMLError):
            return "UNPARSEABLE_STRUCTURED_INCREMENT"
    elif value is None and suffix == ".py":
        try:
            parsed = ast.parse(text)
        except SyntaxError:
            return "UNPARSEABLE_CODE_OR_RENAMED_DATA"
        literal_objects: list[object] = []
        for node in ast.walk(parsed):
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                if any(
                    isinstance(target, ast.Name)
                    and target.id.lower() in {"source_path", "source_file", "input_path"}
                    for target in targets
                ):
                    item = node.value
                    if isinstance(item, ast.Call) and item.args:
                        item = item.args[0]
                    if (
                        isinstance(item, ast.Constant)
                        and isinstance(item.value, str)
                        and RAW_PATH.search(item.value)
                    ):
                        literal_objects.append({"source_path": item.value})
            if isinstance(node, ast.Dict):
                # Inspect only scalar literals, not annotations/computed output.
                literal = {
                    key.value: item.value
                    for key, item in zip(node.keys, node.values, strict=True)
                    if isinstance(key, ast.Constant)
                    and isinstance(key.value, str)
                    and isinstance(item, ast.Constant)
                }
                literal_objects.append(literal)
        value = literal_objects
    if _source_object(value):
        return "REAL_SOURCE_PATH_REVIEW_REQUIRED"
    if isinstance(value, dict) and value.get("data_class") in {
        "SYNTHETIC_ONLY",
        "SYNTHETIC_TEST_FIXTURE",
    }:
        return "UNVERIFIED_SYNTHETIC_CLAIM"
    if _business_object(value):
        return "POSSIBLE_BUSINESS_LITERALS_REVIEW_REQUIRED"
    # Text/JS/Markdown are not a safe rename destination for a receipt table.
    lines = text.splitlines()
    if len(lines) > 1 and suffix != ".py":
        fields = re.split(r"[,|\t]", lines[0])
        quantity_columns = [i for i, word in enumerate(fields) if QUANTITIES.search(word)]
        if len(fields) > 1 and quantity_columns:
            for line in lines[1:]:
                cells = re.split(r"[,|\t]", line)
                if any(
                    i < len(cells) and NUMBER.fullmatch(cells[i].strip().strip("\"'"))
                    for i in quantity_columns
                ):
                    return "RENAMED_BUSINESS_TABLE_REVIEW_REQUIRED"
    if suffix in {".ts", ".tsx", ".js", ".md", ".txt", ".html"}:
        if re.search(r'["\'](?:weight_kg|area_mu|actual_kg|total_kg)["\']\s*:\s*\d', text):
            return "POSSIBLE_BUSINESS_LITERALS_REVIEW_REQUIRED"
        if re.search(r"(?m)^\s*(?:weight_kg|area_mu|actual_kg|total_kg)\s*:\s*\d", text):
            return "RENAMED_BUSINESS_TABLE_REVIEW_REQUIRED"
    return None


def inspect(repo: Path, base: str, head: str = "HEAD") -> dict[str, object]:
    from scripts.ci.check_workbook_distribution import WORKBOOK_BLOBS, WORKBOOK_NAMES

    before, after = tree(repo, base), tree(repo, head)
    changed = sorted(name for name in after if after[name] != before.get(name))
    violations: list[dict[str, str]] = []
    verified: list[str] = []
    inputs = {
        "docs/tech-debt/td01c-public-derived-risk-register.csv",
        "docs/tech-debt/td01c-public-derived-audit-summary.json",
        "docs/tech-debt/td01b-public-ref-exposure-r1.csv",
        "docs/tech-debt/td01c-historical-contract-migration-plan-r1.md",
    }
    for path in sorted(inputs & before.keys()):
        if after.get(path) != before[path]:
            violations.append({"path": path, "reason": "PINNED_REVIEW_BASELINE_CHANGED"})
    from backend.app.etl.history.privacy_boundary import classify

    historical = {
        row["PATH"]
        for row in classify(ROOT).rows
        if row["ASSET_CLASS"] != "CODE_SCHEMA_OR_POSSIBLE_LITERAL"
    }
    for path in sorted((before.keys() - after.keys()) & historical - inputs):
        violations.append({"path": path, "reason": "HISTORICAL_CANDIDATE_REMOVED_REVIEW_REQUIRED"})
    candidates: set[str] | None = None
    metadata: dict[str, bytes] | None = None
    # A new seed is admitted only through a byte-identical regenerated manifest,
    # not its self-declared labels or weight Hashes. Workbooks remain unopened.
    seeds = {41}
    for path in changed:
        kind, oid = after[path]
        if (
            kind != "blob"
            or PurePosixPath(path).suffix.lower() not in {".json", ".txt", ".md", ".py"}
            or oid in COMPRESSED_BLOBS | WORKBOOK_BLOBS
        ):
            continue
        try:
            data = read_public_text(repo, oid)
            value = json.loads(data)
            if isinstance(value, dict) and value.get("data_class") == "SYNTHETIC_ONLY":
                seed = value.get("seed")
                if type(seed) is int and 0 <= seed < 2**31:
                    generated = synthetic_outputs(seed)
                    if data == generated["SYNTHETIC_ONLY-manifest.json"]:
                        seeds.add(seed)
        except (OSError, ValueError, subprocess.CalledProcessError):
            pass  # Not clearance; the main pass below still rejects invalid data.
    for path in changed:
        kind, oid = after[path]
        reason = None
        if oid in WORKBOOK_BLOBS or PurePosixPath(path).name in WORKBOOK_NAMES:
            reason = "HISTORICAL_WORKBOOK_REINTRODUCTION"
        elif oid in COMPRESSED_BLOBS:
            reason = "COMPRESSED_SOURCE_IDENTITY_REQUIRES_OWNER"
        elif kind != "blob" or PurePosixPath(path).suffix.lower() in {
            ".gz",
            ".zip",
            ".xls",
            ".parquet",
            ".bz2",
            ".xz",
        }:
            reason = "UNVERIFIED_DATA_ARTIFACT"
        elif path in before and path not in inputs:
            if path in historical:
                reason = "HISTORICAL_CANDIDATE_CHANGED_REVIEW_REQUIRED"
        if reason is None:
            try:
                if candidates is None:
                    candidates = {
                        hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
                        for seed in sorted(seeds)
                        for data in synthetic_outputs(seed).values()
                    }
                if oid in candidates:
                    verified.append(path)
                    continue
                if path.startswith("docs/tech-debt/td01d-"):
                    if metadata is None:
                        metadata = _metadata_outputs()
                    if PurePosixPath(path).name in metadata:
                        expected = metadata[PurePosixPath(path).name]
                        expected_oid = hashlib.sha1(
                            b"blob " + str(len(expected)).encode() + b"\0" + expected
                        ).hexdigest()
                        if oid == expected_oid:
                            continue
                        reason = "CLASSIFICATION_OUTPUT_NOT_REPRODUCIBLE"
                if reason is None:
                    reason = (
                        "UNVERIFIED_DATA_ARTIFACT"
                        if PurePosixPath(path).suffix.lower()
                        not in {
                            ".py",
                            ".ts",
                            ".tsx",
                            ".js",
                            ".json",
                            ".yaml",
                            ".yml",
                            ".md",
                            ".txt",
                            ".csv",
                            ".html",
                            ".toml",
                            ".ini",
                            ".sh",
                            ".css",
                            ".svg",
                        }
                        else text_reason(path, read_public_text(repo, oid))
                    )
            except (OSError, ValueError, subprocess.CalledProcessError):
                reason = "INCREMENT_OR_PRODUCER_REVIEW_REQUIRED"
        if reason is not None:
            violations.append({"path": path, "reason": reason})
    return {
        "status": "REVIEW_REQUIRED" if violations else "PASS",
        "violations": violations,
        "changed_path_count": len(changed),
        "verified_synthetic_paths": verified,
        "unchanged_history_publication_approved": False,
        "historical_exposure_eliminated": False,
        "raw_assets_opened": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--base", default=BASELINE)
    parser.add_argument("--head", default="HEAD")
    args = parser.parse_args()
    try:
        result = inspect(args.repo, args.base, args.head)
    except (OSError, ValueError, subprocess.CalledProcessError):
        result = {"status": "REVIEW_REQUIRED", "reason": "REVIEW_BASE_UNAVAILABLE_OR_INVALID"}
    print(json.dumps(result, sort_keys=True, indent=2))
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
